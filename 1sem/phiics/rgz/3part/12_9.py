import math

# Дано
U = 20          # В
d = 25e-6       # м
L = 1           # м

# Константы
h = 6.626e-34   # Дж·с
m_e = 9.109e-31 # кг
e = 1.602e-19   # Кл

# Длина волны де Бройля
lambda_e = h / math.sqrt(2 * m_e * e * U)
print(f"Длина волны электрона: {lambda_e*1e9:.3f} нм")

# Расстояние между максимумами
delta_y = lambda_e * L / d
print(f"Расстояние между максимумами: {delta_y*1e6:.3f} мкм")