# Дано
L_l = 1.83e-32          # Дж·с

# Константы
e = 1.602e-19           # Кл
m_e = 9.109e-31         # кг
mu_B = 9.274e-24        # Дж/Тл (магнетон Бора)

# Магнитный момент
M_l = (e / (2 * m_e)) * L_l
print(f"Магнитный момент M_l = {M_l:.3e} Дж/Тл")

# В магнетонах Бора
print(f"Это составляет {M_l / mu_B:.1f} μ_B")